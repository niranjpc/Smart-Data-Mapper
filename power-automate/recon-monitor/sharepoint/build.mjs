// Builds sharepoint/Reconciliation-Monitor.aspx — one self-contained live page — from the shared sources:
//   node sharepoint/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '..');
const read = (p) => readFileSync(path.join(root, p), 'utf8');
const tpl = read('dashboard/recon-monitor.template.html');
const open = tpl.indexOf('<script>') + 8, close = tpl.lastIndexOf('</script>');
const lines = tpl.slice(open, close).split('\n');
const at = lines.findIndex((l) => l.startsWith('const D="__RECON_DATA__";'));
if (at < 0 || !lines[at + 1].startsWith('if(typeof D==="string")')) throw new Error('template data placeholder not found');
const page = lines.slice(0, at).concat(lines.slice(at + 2)).join('\n');
const engine = stripTypeScriptTypes(read('office-scripts/ReconMonitor.ts')).split('\n').map((l) => l.replace(/\s+$/, '')).join('\n').replace(/\n{3,}/g, '\n\n');
const out = tpl.slice(0, open) +
  '\n/* GENERATED by sharepoint/build.mjs — edit the sources, not this file. */\n' +
  '/* ===== rules engine (same code as office-scripts/ReconMonitor.ts) ===== */\n' + engine +
  '\n/* ===== workbook reader ===== */\n' + read('sharepoint/src/xlsx-reader.js') +
  '\n/* ===== dashboard ===== */\nfunction startDashboard(D){' + page + '}\n' +
  '\n/* ===== live loader ===== */\n' + read('sharepoint/src/loader.js') + tpl.slice(close);
writeFileSync(path.join(here, 'Reconciliation-Monitor.aspx'), out);
console.log('sharepoint/Reconciliation-Monitor.aspx', Math.round(out.length / 1024) + ' KB');
